import { readFileSync, writeFileSync } from 'node:fs'

const [wasmPath, outPath] = process.argv.slice(2)
if (!wasmPath || !outPath) {
  console.error('usage: embed-wasm.mjs <wasm> <out.js>')
  process.exit(1)
}

const wasmBase64 = readFileSync(wasmPath).toString('base64')
writeFileSync(
  outPath,
  `// Generated by scripts/embed-wasm.mjs. Do not edit.\nexport const wasmBase64 = '${wasmBase64}'\n`,
)
